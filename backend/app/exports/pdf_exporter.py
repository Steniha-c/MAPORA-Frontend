"""Export Floor Plan and Project Summary to Architectural PDF Report."""

from datetime import datetime, timezone
import io
from typing import Any, Dict, List
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle


def export_floor_plan_to_pdf(
    floor_plan_data: Dict[str, Any],
    project_name: str = "Project",
    project_location: str = "Survey Site",
) -> bytes:
    """
    Generate professional multi-page architectural report in PDF format.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Heading1"],
        fontSize=22,
        leading=26,
        textColor=colors.HexColor("#0f172a"),
        fontName="Helvetica-Bold",
    )
    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["Normal"],
        fontSize=11,
        leading=15,
        textColor=colors.HexColor("#64748b"),
    )
    heading2_style = ParagraphStyle(
        "ReportH2",
        parent=styles["Heading2"],
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#1e293b"),
        spaceBefore=14,
        spaceAfter=8,
    )

    elements = []

    # Header
    elements.append(Paragraph(f"MAPORA Spatial Mapping Report", title_style))
    elements.append(Paragraph(f"Project: <b>{project_name}</b> | Location: {project_location}", subtitle_style))
    elements.append(Paragraph(f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}", subtitle_style))
    elements.append(Spacer(1, 15))

    rooms = floor_plan_data.get("rooms", [])
    walls = floor_plan_data.get("walls", [])

    total_area = sum(r.get("areaSquareMeters", 0.0) or 0.0 for r in rooms)

    # Key Metrics Table
    metrics_data = [
        ["Metric", "Measured Value"],
        ["Rooms Detected", str(len(rooms))],
        ["Wall Segments", str(len(walls))],
        ["Total Measured Area", f"{total_area:.1f} m²"],
        ["Coordinate System", floor_plan_data.get("coordinateSystem", "normalized-cartesian-2d")],
        ["Measurement Units", floor_plan_data.get("units", "meters")],
    ]
    metrics_table = Table(metrics_data, colWidths=[200, 320])
    metrics_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e293b")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.whitesmoke),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 10),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 6),
        ("BACKGROUND", (0, 1), (-1, -1), colors.HexColor("#f8fafc")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
        ("FONTSIZE", (0, 1), (-1, -1), 9),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    elements.append(metrics_table)
    elements.append(Spacer(1, 20))

    # Room Schedule
    elements.append(Paragraph("Room Schedule & Spatial Geometry", heading2_style))
    schedule_data = [["Room ID", "Name", "Bounding Width", "Bounding Length", "Area"]]

    for r in rooms:
        b = r.get("bounds", {})
        schedule_data.append([
            r.get("id", "-"),
            r.get("name", "Room"),
            f"{b.get('width', 0):.2f} m",
            f"{b.get('height', 0):.2f} m",
            f"{r.get('areaSquareMeters', 0):.2f} m²",
        ])

    if len(schedule_data) == 1:
        schedule_data.append(["-", "No rooms segmented", "-", "-", "-"])

    schedule_table = Table(schedule_data, colWidths=[100, 140, 95, 95, 90])
    schedule_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#334155")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.whitesmoke),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 9),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 5),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f1f5f9")]),
        ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
        ("FONTSIZE", (0, 1), (-1, -1), 9),
    ]))
    elements.append(schedule_table)
    elements.append(Spacer(1, 25))

    elements.append(Paragraph(
        "Disclaimer: Indoor spatial map generated by MAPORA monocular computer vision pipeline. "
        "Measured dimensions are subject to monocular scale calibration tolerances.",
        subtitle_style,
    ))

    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()
